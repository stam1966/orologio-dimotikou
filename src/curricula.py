def norm(s):
    s = unicodedata.normalize('NFD', str(s or ''))
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn').upper().replace('΄', '').replace("'", '')
    return ' '.join(s.replace('-', ' - ').split()).replace(' - ', ' - ')


def _key(s):
    return norm(s).replace(' - ', ' ').replace('-', ' ').replace('.', '')


def match(subjects, name):
    """id υπάρχοντος μαθήματος που αντιστοιχεί στο επίσημο όνομα (ή '')."""
    by = {}
    for s in subjects:
        for k in (s.get('name'), s.get('short')):
            if k:
                by.setdefault(_key(k), s['id'])
    for cand in [name] + ALIASES.get(norm(name), []):
        sid = by.get(_key(cand))
        if sid:
            return sid
    return ''


def listing(p=None):
    """Τα πρότυπα για το UI, με προτεινόμενη αντιστοίχιση στα μαθήματα του έργου."""
    subs = (p or {}).get('subjects', [])
    out = []
    for t in TEMPLATES:
        used = set(); rows = []
        for name, hrs, opt in t['subjects']:
            sid = match(subs, name)
            if sid in used:
                sid = ''
            used.add(sid)
            optg = sorted(g for (tid, n, g) in OPTIONAL_IN if tid == t['id'] and n == name)
            rows.append({'name': name, 'hours': hrs, 'optional': opt, 'optional_grades': optg, 'match': sid})
        out.append({k: t[k] for k in ('id', 'level', 'title', 'source', 'note', 'total')} | {'subjects': rows})
    return out


def check_totals():
    """Λίστα αποκλίσεων από τα σύνολα του ΦΕΚ (για tests)."""
    bad = []
    for t in TEMPLATES:
        for g, tot in t['total'].items():
            s = sum(h.get(g, 0) for n, h, o in t['subjects'] if not o or n == 'Γαλλικά')  # 2η ξένη μία φορά
            if t['id'] == 'gel' and g in ('Β', 'Γ'):
                s += {'Β': 5, 'Γ': 18}[g]  # μία ομάδα προσανατολισμού
            if s != tot:
                bad.append((t['id'], g, s, tot))
    return bad
